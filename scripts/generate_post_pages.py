def update_sitemap(entries):
    if not SITEMAP.exists():
        return
    text = SITEMAP.read_text(encoding="utf-8")
    text = re.sub(re.escape(SITEMAP_START) + r"[\s\S]*?" + re.escape(SITEMAP_END) + r"\n?", "", text)
    urls = "".join(
        f"  <url>\n    <loc>{SITE}/blog/{esc(slug_for(e))}</loc>\n"
        f"    <lastmod>{esc(e.get('date', ''))}</lastmod>\n"
        f"    <changefreq>yearly</changefreq>\n    <priority>0.5</priority>\n  </url>\n"
        for e in entries
    )
    block = f"{SITEMAP_START}\n{urls}{SITEMAP_END}\n"
    text = text.replace("</urlset>", block + "</urlset>")
    SITEMAP.write_text(text, encoding="utf-8")


def main():
    manifest_path = BLOG_DIR / "index.json"
    if not manifest_path.exists():
        print("blog/index.json not found")
        return
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    entries = [e for e in manifest if e.get("file") and Path(e["file"]).exists()]

    keep = set()
    for i, entry in enumerate(entries):
        markdown = Path(entry["file"]).read_text(encoding="utf-8")
        newer = entries[i - 1] if i > 0 else None
        older = entries[i + 1] if i + 1 < len(entries) else None
        out = BLOG_DIR / f"{slug_for(entry)}.html"
        out.write_text(page_html(entry, render_markdown(markdown), newer, older), encoding="utf-8")
        keep.add(out.name)

    # Remove pages for posts that have aged out of the manifest
    for stale in BLOG_DIR.glob("*.html"):
        if stale.name not in keep and "generate_post_pages.py" in stale.read_text(encoding="utf-8")[:300]:
            stale.unlink()

    update_sitemap(entries)
    print(f"Generated {len(entries)} post pages")


if __name__ == "__main__":
    main()
