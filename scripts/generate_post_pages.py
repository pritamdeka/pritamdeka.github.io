"""Generate a static, shareable HTML page for every weekly blog post.

Reads blog/index.json and each post's markdown, then writes
blog/<slug>.html (served at https://pritamdeka.com/blog/<slug>) with its own
title, description, Open Graph / Twitter tags and BlogPosting JSON-LD, so
link previews on LinkedIn, X, WhatsApp etc. show the actual post.

Also rewrites the blog-post block of sitemap.xml.

Stdlib only; safe to run locally:  python scripts/generate_post_pages.py
"""

import html
import json
import re
from pathlib import Path
from urllib.parse import quote

SITE = "https://pritamdeka.com"
AUTHOR = "Pritam Deka"
DEFAULT_IMAGE = f"{SITE}/profile.jpg"
BLOG_DIR = Path("blog")
SITEMAP = Path("sitemap.xml")
SITEMAP_START = "  <!-- blog-posts:start (generated by scripts/generate_post_pages.py) -->"
SITEMAP_END = "  <!-- blog-posts:end -->"


def esc(value):
    return html.escape(str(value or ""), quote=True)


def slug_for(entry):
    return Path(entry["file"]).stem


# ---- Markdown rendering (mirrors window.renderDigestMarkdown in blog.html) ----

def strip_raw_html(value):
    value = re.sub(r"<(script|style|svg|picture|iframe|video|audio)\b[\s\S]*?</\1>", " ", value, flags=re.I)
    value = re.sub(r"<img\b[^>]*>", " ", value, flags=re.I)
    value = re.sub(r"<br\s*/?>|</p\s*>|</h[1-6]\s*>", "\n", value, flags=re.I)
    value = re.sub(r"</?[a-z][a-z0-9-]*(?:\s+[^>]*)?>", " ", value, flags=re.I)
    return re.sub(r"\s+", " ", value).strip()


def inline(value):
    out = html.escape(strip_raw_html(value), quote=True)
    out = re.sub(r"\[([^\]]+)\]\((https?://[^)\s]+)\)",
                 r'<a href="\2" target="_blank" rel="noopener noreferrer">\1</a>', out)
    out = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", out)
    out = re.sub(r"_([^_]+)_", r"<em>\1</em>", out)
    return out


def render_markdown(markdown):
    output, toc = [], []
    list_open = False

    def close_list():
        nonlocal list_open
        if list_open:
            output.append("</ul>")
            list_open = False

    for line in markdown.replace("\r\n", "\n").replace("\r", "\n").split("\n"):
        value = line.strip()
        if not value:
            close_list()
        elif value.startswith("## "):
            close_list()
            heading = value[3:]
            anchor = "blog-" + re.sub(r"[^a-z0-9]+", "-", heading.lower()).strip("-")
            toc.append((anchor, heading))
            output.append(f'<h2 id="{anchor}">{inline(heading)}</h2>')
        elif value.startswith("### "):
            close_list()
            output.append(f"<h3>{inline(value[4:])}</h3>")
        elif value.startswith("# "):
            close_list()
            output.append(f"<h1>{inline(value[2:])}</h1>")
        elif re.fullmatch(r"_.+_", value):
            close_list()
            output.append(f'<p class="blog-standfirst">{inline(value[1:-1])}</p>')
        elif value == "---":
            close_list()
            output.append("<hr>")
        elif value.startswith("- "):
            if not list_open:
                output.append("<ul>")
                list_open = True
            output.append(f"<li>{inline(value[2:])}</li>")
        else:
            close_list()
            output.append(f"<p>{inline(value)}</p>")
    close_list()

    if toc:
        links = "".join(f'<a href="#{a}">{inline(h)}</a>' for a, h in toc)
        toc_html = ('<nav class="blog-toc" aria-label="Article contents">'
                    f"<strong>In this briefing</strong>{links}</nav>")
        first = next((i for i, item in enumerate(output) if item.startswith("<h2")), None)
        if first is not None:
            output.insert(first, toc_html)
    return "".join(output)


# ---- Page template ----

def share_bar(url, title):
    """Same markup as window.buildShareBar in dynamic.js."""
    u, t = quote(url, safe=""), quote(title, safe="")

    def link(href, icon, label):
        return (f'<a class="blog-share-btn" target="_blank" rel="noopener noreferrer" '
                f'href="{esc(href)}"><i class="{icon}"></i> {label}</a>')

    return (
        '<div class="blog-share" aria-label="Share this post">'
        '<span class="blog-share-label"><i class="fas fa-share-nodes"></i> Share</span>'
        f'<button type="button" class="blog-share-btn blog-share-native" data-share="native" data-url="{esc(url)}" '
        f'data-title="{esc(title)}"><i class="fas fa-arrow-up-from-bracket"></i> Share…</button>'
        + link(f"https://www.linkedin.com/sharing/share-offsite/?url={u}", "fab fa-linkedin", "LinkedIn")
        + link(f"https://twitter.com/intent/tweet?text={t}&url={u}", "fab fa-x-twitter", "X")
        + link(f"https://bsky.app/intent/compose?text={t}%20{u}", "fas fa-cloud", "Bluesky")
        + link(f"https://wa.me/?text={t}%20{u}", "fab fa-whatsapp", "WhatsApp")
        + f'<a class="blog-share-btn" href="{esc(f"mailto:?subject={t}&body={u}")}"><i class="fas fa-envelope"></i> Email</a>'
        f'<button type="button" class="blog-share-btn" data-share="copy" data-url="{esc(url)}"><i class="fas fa-link"></i> Copy link</button>'
        '</div>'
    )


